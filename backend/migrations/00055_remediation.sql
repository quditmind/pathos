-- +goose Up
-- PATHOS 3.0, M8: remediation workspace and fix verification
-- (docs/aspm/PATHOS_DATABASE_DESIGN.md "Remediation items and gate decisions").
--
-- A remediation item groups one or more findings of one repository with an
-- owner, a due date (from the SLA engine unless set by hand), a status, a
-- root cause and a link to a fix pull request. An item closes only when a
-- verification proves the fix (CHECK below): a targeted rescan of the
-- affected files with the finding's scanner, or a finished scan of the
-- repository, no longer reports its findings. Verifications keep the
-- before-and-after evidence and are immutable once finished.
-- Keys are UUIDv7 generated by the application. Tenant isolation follows
-- docs/MULTI_TENANCY.md (pathos_apply_app_grants below).

-- Composite keys (organization_id, id) on the referenced tables, where
-- migration 00042 did not already add them.
-- +goose StatementBegin
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['applications', 'repositories', 'users', 'findings', 'scan_jobs', 'fix_pull_requests', 'ai_fix_proposals'] LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_index i
            WHERE i.indrelid = t::regclass AND i.indisunique AND i.indpred IS NULL AND i.indexprs IS NULL AND i.indnatts = 2
              AND (SELECT array_agg(attname::text ORDER BY attname) FROM pg_attribute
                   WHERE attrelid = t::regclass AND attnum = ANY (i.indkey)) = ARRAY['id', 'organization_id']
        ) THEN
            EXECUTE format('CREATE UNIQUE INDEX %I ON %I (organization_id, id)', 'org_ref_uq_' || substr(md5(t || '.id'), 1, 12), t);
            EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I UNIQUE USING INDEX %I', t,
                           'org_ref_uq_' || substr(md5(t || '.id'), 1, 12), 'org_ref_uq_' || substr(md5(t || '.id'), 1, 12));
        END IF;
    END LOOP;
END $$;
-- +goose StatementEnd

CREATE TABLE remediation_items (
    id                  uuid PRIMARY KEY,
    organization_id     uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    application_id      uuid,
    repository_id       uuid,
    title               text NOT NULL CHECK (length(title) BETWEEN 1 AND 300),
    kind                text NOT NULL CHECK (kind IN ('code_fix', 'dependency_upgrade', 'configuration', 'threat_mitigation', 'design_change')),
    status              text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'planned', 'in_progress', 'fix_submitted',
                            'verifying', 'closed', 'wont_fix')),
    priority            text NOT NULL DEFAULT 'medium' CHECK (priority IN ('critical', 'high', 'medium', 'low')),
    root_cause          text NOT NULL DEFAULT '' CHECK (length(root_cause) <= 4000),
    owner_id            uuid,
    due_at              timestamptz,
    -- sla: the earliest SLA deadline of the item's findings; manual: set by a person.
    due_source          text NOT NULL DEFAULT 'none' CHECK (due_source IN ('sla', 'manual', 'none')),
    fix_pull_request_id uuid,
    ai_fix_id           uuid,
    closed_at           timestamptz,
    -- The verification that proved the fix (rule: an item closes only on proof).
    closed_by_verification_id uuid,
    created_by          uuid,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, id),
    CHECK (application_id IS NOT NULL OR repository_id IS NOT NULL),
    CHECK (status <> 'closed' OR (closed_by_verification_id IS NOT NULL AND closed_at IS NOT NULL)),
    FOREIGN KEY (organization_id, application_id) REFERENCES applications(organization_id, id) ON DELETE CASCADE,
    FOREIGN KEY (organization_id, repository_id) REFERENCES repositories(organization_id, id) ON DELETE CASCADE,
    FOREIGN KEY (organization_id, owner_id) REFERENCES users(organization_id, id) ON DELETE SET NULL (owner_id),
    FOREIGN KEY (organization_id, fix_pull_request_id) REFERENCES fix_pull_requests(organization_id, id) ON DELETE SET NULL (fix_pull_request_id),
    FOREIGN KEY (organization_id, ai_fix_id) REFERENCES ai_fix_proposals(organization_id, id) ON DELETE SET NULL (ai_fix_id)
);
CREATE INDEX remediation_items_list_idx ON remediation_items (organization_id, status, due_at);
CREATE INDEX remediation_items_repo_idx ON remediation_items (organization_id, repository_id, status);
CREATE INDEX remediation_items_owner_idx ON remediation_items (organization_id, owner_id) WHERE owner_id IS NOT NULL;
CREATE INDEX remediation_items_fixpr_idx ON remediation_items (fix_pull_request_id) WHERE fix_pull_request_id IS NOT NULL;

CREATE TABLE remediation_item_findings (
    organization_id uuid NOT NULL,
    item_id         uuid NOT NULL,
    finding_id      uuid NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (item_id, finding_id),
    FOREIGN KEY (organization_id, item_id) REFERENCES remediation_items(organization_id, id) ON DELETE CASCADE,
    FOREIGN KEY (organization_id, finding_id) REFERENCES findings(organization_id, id) ON DELETE CASCADE
);
CREATE INDEX remediation_item_findings_finding_idx ON remediation_item_findings (finding_id);

-- Before-and-after evidence of a fix. A targeted rescan is leased by a
-- worker that has the finding's scanner (same machinery as verified AI
-- fixes: clone, run the scanner on the affected files only, compare).
CREATE TABLE remediation_verifications (
    id                  uuid PRIMARY KEY,
    organization_id     uuid NOT NULL,
    item_id             uuid NOT NULL,
    repository_id       uuid NOT NULL,
    trigger             text NOT NULL CHECK (trigger IN ('manual', 'fix_pr_merged', 'existing_scan')),
    status              text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'running', 'completed', 'failed')),
    result              text CHECK (result IN ('fixed', 'still_present', 'regressed', 'inconclusive')),
    -- The scanners that reported the findings (each re-runs on the files),
    -- their configuration from the scan profile, and the versions that ran.
    scanner_keys        text[] NOT NULL DEFAULT '{}',
    scanner_configs     jsonb NOT NULL DEFAULT '{}',
    scanner_versions    jsonb NOT NULL DEFAULT '{}',
    files               text[] NOT NULL DEFAULT '{}',
    -- The findings to prove gone: [{finding_id, rule_id, file, line, fingerprint, status}].
    targets             jsonb NOT NULL DEFAULT '[]',
    before_scan_job_id  uuid,
    before_commit       text NOT NULL DEFAULT '' CHECK (length(before_commit) <= 64),
    before_count        integer,
    after_scan_job_id   uuid,
    after_ref           text NOT NULL DEFAULT '' CHECK (length(after_ref) <= 255),
    after_commit        text NOT NULL DEFAULT '' CHECK (length(after_commit) <= 64),
    after_count         integer,
    fix_pull_request_id uuid,
    -- Per-finding verdicts, regressions (new results in the affected files),
    -- scanner results before and after.
    evidence            jsonb NOT NULL DEFAULT '{}',
    failure_reason      text NOT NULL DEFAULT '' CHECK (length(failure_reason) <= 2000),
    leased_by           uuid,
    lease_expires_at    timestamptz,
    attempts            integer NOT NULL DEFAULT 0,
    requested_by        uuid,
    created_at          timestamptz NOT NULL DEFAULT now(),
    finished_at         timestamptz,
    UNIQUE (organization_id, id),
    CHECK (status <> 'completed' OR result IS NOT NULL),
    FOREIGN KEY (organization_id, item_id) REFERENCES remediation_items(organization_id, id) ON DELETE CASCADE,
    FOREIGN KEY (organization_id, repository_id) REFERENCES repositories(organization_id, id) ON DELETE CASCADE,
    FOREIGN KEY (organization_id, before_scan_job_id) REFERENCES scan_jobs(organization_id, id) ON DELETE SET NULL (before_scan_job_id),
    FOREIGN KEY (organization_id, after_scan_job_id) REFERENCES scan_jobs(organization_id, id) ON DELETE SET NULL (after_scan_job_id),
    FOREIGN KEY (organization_id, fix_pull_request_id) REFERENCES fix_pull_requests(organization_id, id) ON DELETE SET NULL (fix_pull_request_id),
    FOREIGN KEY (organization_id, requested_by) REFERENCES users(organization_id, id) ON DELETE SET NULL (requested_by)
);
CREATE INDEX remediation_verifications_item_idx ON remediation_verifications (item_id, created_at DESC);
CREATE INDEX remediation_verifications_queue_idx ON remediation_verifications (organization_id, created_at) WHERE status IN ('queued', 'running');

ALTER TABLE remediation_items ADD CONSTRAINT remediation_items_closed_by_fk
    FOREIGN KEY (organization_id, closed_by_verification_id) REFERENCES remediation_verifications(organization_id, id);

-- Finished evidence is immutable (only references to deleted scans may be cleared).
-- +goose StatementBegin
CREATE FUNCTION pathos_remediation_verification_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status IN ('completed', 'failed') AND (NEW.status, NEW.result, NEW.evidence, NEW.before_commit, NEW.after_commit,
        NEW.before_count, NEW.after_count, NEW.targets, NEW.files, NEW.item_id, NEW.organization_id)
        IS DISTINCT FROM (OLD.status, OLD.result, OLD.evidence, OLD.before_commit, OLD.after_commit,
        OLD.before_count, OLD.after_count, OLD.targets, OLD.files, OLD.item_id, OLD.organization_id) THEN
        RAISE EXCEPTION 'a finished remediation verification is immutable' USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;
-- +goose StatementEnd
CREATE TRIGGER remediation_verifications_immutable BEFORE UPDATE ON remediation_verifications
    FOR EACH ROW EXECUTE FUNCTION pathos_remediation_verification_immutable();

-- Saved views of the workspace (filters), private or shared with the organization.
CREATE TABLE remediation_views (
    id              uuid PRIMARY KEY,
    organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    owner_id        uuid NOT NULL,
    name            text NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
    filters         jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(filters) = 'object' AND pg_column_size(filters) <= 4096),
    shared          boolean NOT NULL DEFAULT false,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, owner_id, name),
    FOREIGN KEY (organization_id, owner_id) REFERENCES users(organization_id, id) ON DELETE CASCADE
);

SELECT pathos_apply_app_grants();

