-- PATHOS 3.0, M9: continuous monitoring feed and architecture drift
-- (docs/aspm/PATHOS_DATABASE_DESIGN.md "Monitoring events and architecture
-- drift"; flag continuous_monitoring).
--
-- monitoring_events is the per-organization feed of the lifecycle feedback
-- loops (new commit → rediscovery, dependency change → reassessment,
-- architecture change → threat model, new intelligence → risk re-score,
-- fix merged → verification, gate failure → developer feedback, new
-- findings → AI triage) and other changes. Rows are written by the API and
-- the jobs role only while the organization has the flag on; they are never
-- updated. Every row states its evidence label (rule 5) and carries the
-- references it rests on (snapshot ids, commit, scan job, decision).
--
-- architecture_drifts compares each new CodeGraph snapshot with the
-- previous ready snapshot of the same repository: new or removed routes,
-- API operations, external services, datastores, queues, internet exposure,
-- trust-boundary crossings and components. One row per new snapshot.
--
-- monitoring_settings holds the drift alert switch (off by default).
-- Keys are UUIDv7 generated by the application. Tenant isolation follows
-- docs/MULTI_TENANCY.md (pathos_apply_app_grants below).

CREATE TABLE monitoring_events (
    id              uuid PRIMARY KEY,
    organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    application_id  uuid,
    repository_id   uuid,
    event_type      text NOT NULL CHECK (event_type ~ '^[a-z_]+\.[a-z_]+$' AND length(event_type) <= 64),
    -- The feedback loop of the lifecycle flow (1-7), if any.
    feedback_loop   smallint CHECK (feedback_loop BETWEEN 1 AND 7),
    severity        text NOT NULL DEFAULT 'info' CHECK (severity IN ('critical', 'high', 'medium', 'low', 'info')),
    title           text NOT NULL CHECK (length(title) BETWEEN 1 AND 300),
    summary         text NOT NULL DEFAULT '' CHECK (length(summary) <= 2000),
    evidence_label  text NOT NULL CHECK (evidence_label IN ('verified', 'observed', 'ai_inferred')),
    evidence        jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(evidence) = 'object' AND pg_column_size(evidence) <= 8192),
    subject_type    text NOT NULL DEFAULT '' CHECK (length(subject_type) <= 40),
    subject_id      uuid,
    details         jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(details) = 'object' AND pg_column_size(details) <= 32768),
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, id),
    FOREIGN KEY (organization_id, application_id) REFERENCES applications(organization_id, id) ON DELETE CASCADE,
    FOREIGN KEY (organization_id, repository_id) REFERENCES repositories(organization_id, id) ON DELETE CASCADE
);
CREATE INDEX monitoring_events_feed_idx ON monitoring_events (organization_id, id DESC);
CREATE INDEX monitoring_events_app_idx ON monitoring_events (organization_id, application_id, id DESC) WHERE application_id IS NOT NULL;
CREATE INDEX monitoring_events_repo_idx ON monitoring_events (organization_id, repository_id, id DESC) WHERE repository_id IS NOT NULL;
CREATE INDEX monitoring_events_type_idx ON monitoring_events (organization_id, event_type, id DESC);
CREATE INDEX monitoring_events_age_idx ON monitoring_events (created_at);

CREATE TABLE architecture_drifts (
    id               uuid PRIMARY KEY,
    organization_id  uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    application_id   uuid NOT NULL,
    repository_id    uuid NOT NULL,
    -- NULL: the first snapshot of the repository (baseline, no comparison).
    from_snapshot_id uuid,
    to_snapshot_id   uuid NOT NULL,
    from_commit      text NOT NULL DEFAULT '' CHECK (length(from_commit) <= 64),
    to_commit        text NOT NULL DEFAULT '' CHECK (length(to_commit) <= 64),
    severity         text NOT NULL DEFAULT 'info' CHECK (severity IN ('critical', 'high', 'medium', 'low', 'info')),
    has_changes      boolean NOT NULL DEFAULT false,
    -- {"added_routes": n, "removed_routes": n, ...}
    counts           jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(counts) = 'object' AND pg_column_size(counts) <= 4096),
    -- [{change, category, key, label, detail, file, evidence_label, evidence: [...]}], at most 500 items.
    items            jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(items) = 'array' AND pg_column_size(items) <= 1048576),
    truncated        boolean NOT NULL DEFAULT false,
    created_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, id),
    UNIQUE (to_snapshot_id),
    FOREIGN KEY (organization_id, application_id) REFERENCES applications(organization_id, id) ON DELETE CASCADE,
    FOREIGN KEY (organization_id, repository_id) REFERENCES repositories(organization_id, id) ON DELETE CASCADE,
    FOREIGN KEY (organization_id, to_snapshot_id) REFERENCES codegraph_snapshots(organization_id, id) ON DELETE CASCADE,
    FOREIGN KEY (organization_id, from_snapshot_id) REFERENCES codegraph_snapshots(organization_id, id) ON DELETE SET NULL (from_snapshot_id)
);
CREATE INDEX architecture_drifts_app_idx ON architecture_drifts (organization_id, application_id, id DESC);
CREATE INDEX architecture_drifts_repo_idx ON architecture_drifts (organization_id, repository_id, id DESC);

CREATE TABLE monitoring_settings (
    organization_id          uuid PRIMARY KEY REFERENCES organizations(id) ON DELETE CASCADE,
    drift_alerts             boolean NOT NULL DEFAULT false,
    drift_alert_min_severity text NOT NULL DEFAULT 'high' CHECK (drift_alert_min_severity IN ('critical', 'high', 'medium', 'low')),
    updated_by               uuid,
    updated_at               timestamptz NOT NULL DEFAULT now()
);

